    bool isSelfClosingTag(const std::string& tag)
    {
        return !tag.empty() && tag.back() == '/';
    }

    S32 attrInt(const std::string& tag, const std::string& attr, S32 fallback)
    {
        std::string v;
        return findAttr(tag, attr, v) ? atoi(v.c_str()) : fallback;
    }

