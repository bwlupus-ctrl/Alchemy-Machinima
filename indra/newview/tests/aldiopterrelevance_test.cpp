    // Attribute lookup that respects token boundaries, so a search for
    // name= does not match control_name= or label_width=.
    bool findAttr(const std::string& tag, const std::string& attr,
                  std::string& out)
    {
        const std::string needle = attr + "=\"";
        std::string::size_type pos = 0;
        while ((pos = tag.find(needle, pos)) != std::string::npos)
        {
            const char before = (pos > 0) ? tag[pos - 1] : ' ';
            if (before == ' ' || before == '\t' || before == '\n' ||
                before == '\r')
            {
                std::string::size_type start = pos + needle.size();
                std::string::size_type end = tag.find('"', start);
                if (end == std::string::npos)
                {
                    return false;
                }
                out = tag.substr(start, end - start);
                return true;
            }
            pos += needle.size();
        }
        return false;
    }

    // The relevance model's scope is exactly the 181 CineDiopter* RENDERER
    // inputs.  Floater chrome sits outside it by namespace: CineDiopterUI*
    // (CineDiopterUIActiveOnly -- the section 5.3 display toggle -- and
    // CineDiopterUIRectVersion) is UI state, and the focus-QoL checkboxes
    // bind non-CineDiopter Render* settings (RenderFocusPointCrosshair /
    // RenderFocusPointLocked).  Bindings and resets for those are excluded
    // from the Layer-1 bijection below, exactly as in
    // aldiopterrelevance_oracle.py's _is_modeled_setting().
    bool isModeledSetting(const std::string& setting)
    {
        return setting.compare(0, 11, "CineDiopter") == 0 &&
               setting.compare(0, 13, "CineDiopterUI") != 0;
    }

    struct FloaterScan
    {
        // value-control name -> bound setting (the table's DERIVED column),
        // relevance-model scope only
        std::map<std::string, std::string> mBinding;
        // reset-button name -> commit_callback.parameter, model scope only
        std::map<std::string, std::string> mResets;
    };

    FloaterScan scanFloaterXml()
    {
        const std::string src = readFileOrFail(floaterXmlPath());
        FloaterScan scan;
        std::string::size_type pos = 0;
        while ((pos = src.find('<', pos)) != std::string::npos)
        {
            std::string::size_type end = src.find('>', pos);
            if (end == std::string::npos)
            {
                break;
            }
            const std::string tag = src.substr(pos + 1, end - pos - 1);
            pos = end + 1;

            const std::string::size_type sp = tag.find_first_of(" \t\r\n");
            const std::string elem = tag.substr(0, sp);
            if (elem == "slider" || elem == "combo_box" || elem == "check_box")
            {
                if (elem == "combo_box")
                {
                    // [F8] Spec requirement (design doc section 4.5): every
                    // combo in this floater opts out of wheel-commit --
                    // LLComboBox's wheel handler COMMITS the selection
                    // (llcombobox.cpp:958-997), so a scroll gesture over any
                    // combo would silently mutate render state.
                    std::string name, wheel;
                    findAttr(tag, "name", name);
                    tut::ensure("combo_box '" + name + "' must carry "
                                "wheel_select=\"false\" (design doc 4.5: "
                                "wheel-commit opt-out is mandatory for every "
                                "combo in this floater)",
                                findAttr(tag, "wheel_select", wheel) &&
                                wheel == "false");
                }
                std::string name, setting;
                if (findAttr(tag, "name", name) &&
                    findAttr(tag, "control_name", setting) &&
                    isModeledSetting(setting))
                {
                    tut::ensure("duplicate control " + name,
                                scan.mBinding.count(name) == 0);
                    scan.mBinding[name] = setting;
                }
            }
            else if (elem == "button")
            {
                std::string name, param;
                if (findAttr(tag, "name", name) &&
                    name.compare(0, 4, "rst_") == 0 &&
                    isModeledSetting(name.substr(4)))
                {
                    findAttr(tag, "commit_callback.parameter", param);
                    tut::ensure("duplicate reset " + name,
                                scan.mResets.count(name) == 0);
                    scan.mResets[name] = param;
                }
            }
        }
        return scan;
    }

