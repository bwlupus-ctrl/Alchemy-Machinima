    S32 uiScrollbarSizeDefault()
    {
        const std::string src =
            readFileOrFail(testsDir() + "/../app_settings/settings.xml");
        const std::string::size_type key =
            src.find("<key>UIScrollbarSize</key>");
        tut::ensure("UIScrollbarSize present in settings.xml",
                    key != std::string::npos);
        const std::string::size_type val = src.find("<key>Value</key>", key);
        tut::ensure("UIScrollbarSize has a Value",
                    val != std::string::npos);
        // value is serialized as <real>N</real> (typed S32 upstream)
        const std::string::size_type open = src.find('>', src.find('<', val + 16));
        tut::ensure("UIScrollbarSize value tag parses",
                    open != std::string::npos);
        const S32 size = atoi(src.c_str() + open + 1);
        tut::ensure("UIScrollbarSize default is sane", size > 0 && size < 64);
        return size;
    }

    // `pos` must point just past some opening tag's '>'. Depth-counts
    // further "<panel" opens against "</panel>" closes to find the ONE
    // that matches the panel this position is already inside; returns the
    // inner text (that panel's own children, in ITS coordinate frame) and
    // advances `pos` past the matched "</panel>". False if unmatched
    // (malformed/truncated XML -- the caller should fail the test).
    bool consumePanelBody(const std::string& src, std::string::size_type& pos,
                          std::string& out_inner)
    {
        S32 depth = 1;
        std::string::size_type search_from = pos;
        const std::string::size_type body_start = pos;
        while (depth > 0)
        {
            const std::string::size_type next_open = src.find("<panel", search_from);
            const std::string::size_type next_close = src.find("</panel>", search_from);
            if (next_close == std::string::npos)
            {
                return false;
            }
            if (next_open != std::string::npos && next_open < next_close)
            {
                ++depth;
                search_from = next_open + 6;
            }
            else
            {
                --depth;
                if (depth == 0)
                {
                    out_inner = src.substr(body_start, next_close - body_start);
                    pos = next_close + 8; // strlen("</panel>")
                    return true;
                }
                search_from = next_close + 8;
            }
        }
        return false;
    }

    // Finds the "<panel ...>" whose name="panel_name" attribute matches
    // (wherever in the tag that attribute falls -- the tab-body panels this
    // file generates spread their attributes one per line in a different
    // order than the same-rect band panels do, so a fixed "name=\"X\""
    // substring position cannot be assumed) and returns the span between
    // its '>' and the matching "</panel>".
    bool findNamedPanelSpan(const std::string& src, const std::string& panel_name,
                            std::string& out_inner)
    {
        std::string::size_type pos = 0;
        while ((pos = src.find("<panel", pos)) != std::string::npos)
        {
            const std::string::size_type open_end = src.find('>', pos);
            if (open_end == std::string::npos)
            {
                return false;
            }
            const std::string tag = src.substr(pos, open_end - pos + 1);
            std::string name_s;
            if (findAttr(tag, "name", name_s) && name_s == panel_name)
            {
                std::string::size_type body_pos = open_end + 1;
                return consumePanelBody(src, body_pos, out_inner);
            }
            pos = open_end + 1;
        }
        return false;
    }

    // Every element type Invariant W's walk cares about (all of them carry
    // top=/height=). "panel" is handled specially below (it recurses).
    bool isHeightBearingLeaf(const std::string& elem)
    {
        return elem == "slider" || elem == "combo_box" || elem == "check_box" ||
               elem == "button" || elem == "text" || elem == "view_border";
    }

    // Walks `inner` (one panel's children, in that panel's OWN coordinate
    // frame -- every top= here is relative to it) and returns the max
    // bottom edge (top + height) found, recursing into nested <panel>
    // blocks (same-rect overlay bands) by adding the nested panel's own
    // top to everything found inside it -- exactly how LLView resolves a
    // child's screen position from its parent's. Because every same-rect
    // band's sibling panels share an IDENTICAL top/height by construction
    // (enforced by the generator that authored this XML), visiting every
    // one of them (rather than only the one currently visible="true")
    // still yields the correct worst-case max: a duplicate top+height
    // value cannot move the max, and the invisible siblings are exactly
    // the OTHER modes' content this invariant must also cover.
    S32 maxBottomEdge(const std::string& inner)
    {
        S32 max_bottom = 0;
        std::string::size_type pos = 0;
        while ((pos = inner.find('<', pos)) != std::string::npos)
        {
            if (inner.compare(pos, 4, "<!--") == 0)
            {
                const std::string::size_type cend = inner.find("-->", pos);
                if (cend == std::string::npos) { break; }
                pos = cend + 3;
                continue;
            }
            const std::string::size_type tag_end = inner.find('>', pos);
            if (tag_end == std::string::npos) { break; }
            const std::string tag = inner.substr(pos + 1, tag_end - pos - 1);
            const std::string::size_type after_tag = tag_end + 1;

            if (!tag.empty() && tag[0] == '/')
            {
                pos = after_tag;
                continue;
            }
            const std::string::size_type sp = tag.find_first_of(" \t\r\n");
            const std::string elem = tag.substr(0, sp == std::string::npos ? tag.size() : sp);

            std::string top_s, h_s;
            const bool has_geom = findAttr(tag, "top", top_s) && findAttr(tag, "height", h_s);

            if (elem == "panel" && !isSelfClosingTag(tag))
            {
                std::string body;
                std::string::size_type body_pos = after_tag;
                if (consumePanelBody(inner, body_pos, body))
                {
                    const S32 nested_max = maxBottomEdge(body);
                    if (has_geom)
                    {
                        const S32 top = atoi(top_s.c_str());
                        const S32 h = atoi(h_s.c_str());
                        max_bottom = llmax(max_bottom, top + llmax(h, nested_max));
                    }
                    pos = body_pos;
                    continue;
                }
            }

            if (has_geom && isHeightBearingLeaf(elem))
            {
                const S32 top = atoi(top_s.c_str());
                const S32 h = atoi(h_s.c_str());
                max_bottom = llmax(max_bottom, top + h);
            }
            pos = after_tag;
        }
        return max_bottom;
    }

    // Finds the raw text of the first tag literally "<tag_name" (word-
    // boundary checked so "panel" cannot match "panelfoo"), for reading a
    // handful of top-level attributes off it.
    bool findOpenTagText(const std::string& src, const std::string& tag_name,
                         std::string& out_tag_text)
    {
        const std::string needle = "<" + tag_name;
        std::string::size_type start = 0;
        while ((start = src.find(needle, start)) != std::string::npos)
        {
            const char after = (start + needle.size() < src.size())
                ? src[start + needle.size()] : ' ';
            if (after == ' ' || after == '\t' || after == '\n' || after == '\r' ||
                after == '/' || after == '>')
            {
                const std::string::size_type end = src.find('>', start);
                if (end == std::string::npos) { return false; }
                out_tag_text = src.substr(start, end - start + 1);
                return true;
            }
            start += needle.size();
        }
        return false;
    }

    // Finds the first "<tag_name ...>" whose name="..." attribute equals
    // name_value (scroll_container/panel tags repeat across the 9 tabs, so
    // findOpenTagText's "first occurrence" is not enough for these).
    bool findTagByNameAttr(const std::string& src, const std::string& tag_name,
                          const std::string& name_value, std::string& out_tag_text)
    {
        std::string::size_type pos = 0;
        const std::string needle = "<" + tag_name;
        while ((pos = src.find(needle, pos)) != std::string::npos)
        {
            const std::string::size_type end = src.find('>', pos);
            if (end == std::string::npos) { return false; }
            const std::string tag = src.substr(pos, end - pos + 1);
            std::string name_s;
            if (findAttr(tag, "name", name_s) && name_s == name_value)
            {
                out_tag_text = tag;
                return true;
            }
            pos = end + 1;
        }
        return false;
    }

