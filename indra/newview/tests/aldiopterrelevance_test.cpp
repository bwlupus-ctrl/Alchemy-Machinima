    void addAll(StrSet& out, const StrSet& in)
    {
        out.insert(in.begin(), in.end());
    }

    // ---------------------------------------------------------------------
    // alOracleConsumedSet -- recombine the oracle's per-branch sets with the
    // renderer's gate structure.  Each gate cites the renderer location it
    // mirrors; the per-branch membership itself lives in the .llsd.  This is
    // a second, independent factorization of relevance (branch-union form vs
    // the table's per-control OR-of-AND form) -- the comparison of the two
    // over the sweep corpus is Layer 2's correctness assertion.
    // ---------------------------------------------------------------------

    std::set<std::string> alOracleConsumedSet(const ALDiopterState& st)
    {
        const OracleModel& m = oracleModel();
        StrSet out = m.mMasterEnable;   // Tier 0: relevant even when disabled
        if (!st.mEnabled)
        {
            // pipeline.cpp master-enable gate: everything else is inert
            return out;
        }
        addAll(out, m.mToolShared);     // Tool Mode row (AL_TOOL_BOTH)

        if (st.mToolMode == 0)          // ---- Ultimate Diopter ----
        {
            addAll(out, m.dAlways);
            if (st.mFreeze)
            {
                addAll(out, m.dFreeze);             // Freeze At
            }
            const bool warp = alDiopterEvalPred(PRED_WARP_ARMED, st);
            if (st.mPlacementMode == 0)             // framed
            {
                addAll(out, m.dFramedHeader);       // Shape / Contents combos
                addAll(out, m.dMaskShape[st.mShape]);
                // Size: mask boundary (shapes 2-11) OR refraction radius OR
                // warp annulus outer -- all three discarded under On-Lens
                // (pipeline.cpp:14289-14296; table row 8)
                if (st.mShape >= 2 || st.mGlassProfile > 0 || warp)
                {
                    addAll(out, m.dSize);
                }
                // Hollow as mask onion, shapes 3-11 (table row 20 C1)
                if (st.mShape >= 3)
                {
                    addAll(out, m.dHollow);
                }
            }
            else                                    // On-Lens
            {
                addAll(out, m.dOnLens);
            }
            if (warp)
            {
                // warp dependents + Hollow's annulus-inner path, which is
                // placement-independent (glsl:399; table row 20 C2)
                addAll(out, m.dWarpParams);
                addAll(out, m.dHollow);
            }
            // Wobble Frequency: shared spatial density -- static Edge Wobble
            // OR Motion = Wave, both needing an edge (Codex C2; row 25)
            if (alDiopterEvalPred(PRED_SHAPE_HAS_EDGE, st) &&
                (alDiopterEvalPred(PRED_EDGE_WOBBLE_ARMED, st) ||
                 st.mMotionMode == 3))
            {
                addAll(out, m.dWobbleFreq);
            }
            if (st.mGlassProfile > 0)               // glsl:336
            {
                addAll(out, m.dRefraction);
            }
            if (alDiopterEvalPred(PRED_GHOSTS_ARMED, st))   // glsl:107
            {
                addAll(out, m.dGhosts);
            }
            if (st.mPatternMode >= 1 && st.mPatternMode <= 3)
            {
                addAll(out, m.dFaceted);
            }
            if (alDiopterEvalPred(PRED_SEAM_ARMED, st))     // glsl:90
            {
                addAll(out, m.dSeam);
            }
            const bool powered = alDiopterEvalPred(PRED_LENS_POWERED, st);
            if (powered)                            // pipeline:14249
            {
                addAll(out, m.dCharacter);
            }
            if (alDiopterEvalPred(PRED_ABERRATION_ARMED, st))
            {
                addAll(out, m.dAberration);         // pipeline:14253-14256
                if (st.mContent == 0)
                {
                    addAll(out, m.dAxial);          // zeroed at :14265
                }
            }
            // exactly one of Power / Lens Distance is always dead
            addAll(out, (st.mLensFocusMode == 0) ? m.dPower : m.dLensM);
            if (st.mBaseFocusProvenance == AL_DIOPTER_FOCUS_MANUAL)
            {
                addAll(out, m.dBaseM);              // pipeline:14203-14232
            }
            if (alDiopterEvalPred(PRED_FIELD_CURVE_ARMED, st) ||
                st.mContent == 1)
            {
                addAll(out, m.dFloorMax);           // glsl:592-595 OR rule
            }
            if (st.mContent == 1)
            {
                addAll(out, m.dSpotBlur);           // Sharp Window only
            }
            if (st.mGlassProfile == 0 && st.mContent == 0)
            {
                addAll(out, m.dMagTrim);            // magnify = 1.f otherwise
                if (powered)
                {
                    addAll(out, m.dMagScale);       // multiplicative (row 93)
                }
            }
            addAll(out, m.dMotion[st.mMotionMode]);
            // Pulse Amount: Pulse with Size target, Pulse with Focus target
            // outside Sharp Window (the rack is discarded at :14261-14266),
            // or Heartbeat (row 101)
            if ((st.mMotionMode == 2 &&
                 (st.mPulseTarget == 0 ||
                  (st.mPulseTarget == 1 && st.mContent == 0))) ||
                st.mMotionMode == 10)
            {
                addAll(out, m.dPulseAmt);
            }
            // Wave needs an edge to undulate (Codex C1; row 102)
            if (st.mMotionMode == 3 &&
                alDiopterEvalPred(PRED_SHAPE_HAS_EDGE, st))
            {
                addAll(out, m.dWaveAmp);
            }
            // Stutter Focus is double-guarded (pipeline:14092; row 111)
            if (st.mMotionMode == 5 && st.mContent == 0)
            {
                addAll(out, m.dStutterFocus);
            }
            if (alDiopterEvalPred(PRED_HANDHELD_ARMED, st))
            {
                addAll(out, m.dHandheld);           // pipeline:14154
                if (st.mContent == 0)
                {
                    addAll(out, m.dHandheldFocus);  // pipeline:14165
                }
            }
            addAll(out, m.dSpin[st.mSpinMode]);
            addAll(out, m.dAperture[st.mApertureShape]);
        }
        else                            // ---- Ultimate Kaleidoscope ----
        {
            addAll(out, m.kAlways);
            if (st.mKalFreeze)
            {
                addAll(out, m.kFreeze);
            }
            addAll(out, m.kMode[st.mKalMode]);
            // FX Flow's Tier-C path: cell modes reach ft only through
            // kal_cellScale, a no-op unless Cell Breathe > 0
            // (glsl:110-118; Codex 1.8; row 142 C2)
            if (m.kFlowCellModes.count((S32)st.mKalMode) &&
                alDiopterEvalPred(PRED_CELL_BREATHE_ARMED, st))
            {
                addAll(out, m.kFxFlow);
            }
            addAll(out, m.kMotion[st.mKalMotionMode]);
            // Pulse target Offset also consumes the direction angle
            // (pipeline alKaleidoResolveMotion case 2 else-branch; row 154 C2)
            if (st.mKalMotionMode == 2 && st.mKalPulseTarget == 2)
            {
                addAll(out, m.kPulseOffsetExtra);
            }
            // Wave rows need Motion = Wave AND a wave-evaluating pattern
            // (design doc 2.2 Wv column; rows 159/160)
            if (st.mKalMotionMode == 3 && m.kWaveModes.count((S32)st.mKalMode))
            {
                addAll(out, m.kWave);
            }
            addAll(out, m.kSpin[st.mKalSpinMode]);
            addAll(out, m.kProtect[st.mKalProtectMode]);
            // Protect Center X/Y: disc protect present AND Anchor = Fixed
            // (pipeline:14997-15008; rows 175/176)
            if ((st.mKalProtectMode == 1 || st.mKalProtectMode == 3) &&
                st.mKalProtectAnchor == 1)
            {
                addAll(out, m.kAnchorFixed);
            }
        }
        return out;
    }

    // ---------------------------------------------------------------------
    // The sweep corpus, S0-S8 exactly as design doc 2.3 tabulates.
    // Cardinalities: 4 + 240 + 96 + 576 + 576 + 20 + 12 + 40 + 16 = 1580.
    //
    // Non-axis drivers sit at the settings.xml factory defaults
    // (ALDiopterState's member initializers).  Drivers that no tabulated
    // axis varies -- Freeze, diopter Spin, and the kaleido Spin / Protect /
    // Anchor / PulseTarget / Freeze -- are piggybacked deterministically
    // onto existing axes (documented per sweep below) so the clause-coverage
    // meta-rule can observe their clauses both passing and failing without
    // changing any sweep's advertised cardinality.
    // ---------------------------------------------------------------------

    struct ALSweep
    {
        const char* mName;
        std::vector<ALDiopterState> mStates;
        std::vector<ALDiopterState>::const_iterator begin() const
        {
            return mStates.begin();
        }
        std::vector<ALDiopterState>::const_iterator end() const
        {
            return mStates.end();
        }
    };

    std::vector<ALSweep> buildSweeps()
    {
        std::vector<ALSweep> sweeps;

        // S0 -- enabled x tool-mode: the master-enable Tier-0 gate, and the
        // FALSE state of every ALWAYS clause (the only sweep with Enabled
        // off; without it ALWAYS clauses could never be observed failing).
        {
            ALSweep s; s.mName = "S0";
            for (U32 e = 0; e <= 1; ++e)
            {
                for (U32 t = 0; t <= 1; ++t)
                {
                    ALDiopterState st;
                    st.mEnabled = (e != 0);
                    st.mToolMode = t;
                    s.mStates.push_back(st);
                }
            }
            sweeps.push_back(s);
        }

        // S1 -- shape x placement x profile x warp-armed (12*2*5*2 = 240):
        // the Size / Hollow OR-consumption and D1's On-Lens discard.
        {
            ALSweep s; s.mName = "S1";
            for (U32 sh = 0; sh < 12; ++sh)
                for (U32 pl = 0; pl <= 1; ++pl)
                    for (U32 pr = 0; pr < 5; ++pr)
                        for (U32 w = 0; w <= 1; ++w)
                        {
                            ALDiopterState st;
                            st.mEnabled = true;
                            st.mShape = sh;
                            st.mPlacementMode = pl;
                            st.mGlassProfile = pr;
                            st.mRingFold = w ? 0.5f : 0.f;  // arming input
                            s.mStates.push_back(st);
                        }
            sweeps.push_back(s);
        }

        // S2 -- motion x pulse-target x content x handheld-armed
        // (12*2*2*2 = 96): the Sharp Window guards on Stutter Focus, Focus
        // Breath, Pulse:Focus.  Piggyback: SpinMode = motion % 4 flips the
        // Spin=Constant / Spin{1,2,3} / Spin{3} clauses both ways.
        {
            ALSweep s; s.mName = "S2";
            for (U32 mo = 0; mo < 12; ++mo)
                for (U32 pt = 0; pt <= 1; ++pt)
                    for (U32 c = 0; c <= 1; ++c)
                        for (U32 h = 0; h <= 1; ++h)
                        {
                            ALDiopterState st;
                            st.mEnabled = true;
                            st.mMotionMode = mo;
                            st.mPulseTarget = pt;
                            st.mContent = c;
                            st.mHandheld = h ? 0.6f : 0.f;
                            st.mSpinMode = mo % 4;
                            s.mStates.push_back(st);
                        }
            sweeps.push_back(s);
        }

        // S3 -- shape x placement x motion x edge-wobble-armed
        // (12*2*12*2 = 576): C1 (Wave inert under Full Frame / On-Lens) and
        // C2 (WobbleFreq's OR rule).
        {
            ALSweep s; s.mName = "S3";
            for (U32 sh = 0; sh < 12; ++sh)
                for (U32 pl = 0; pl <= 1; ++pl)
                    for (U32 mo = 0; mo < 12; ++mo)
                        for (U32 w = 0; w <= 1; ++w)
                        {
                            ALDiopterState st;
                            st.mEnabled = true;
                            st.mShape = sh;
                            st.mPlacementMode = pl;
                            st.mMotionMode = mo;
                            st.mWobbleAmt = w ? 0.15f : 0.f;
                            s.mStates.push_back(st);
                        }
            sweeps.push_back(s);
        }

        // S4 -- kal-mode x cell-breathe x kal-motion (24*2*12 = 576): D2's
        // mask and the Tier-C FX Flow path.  Piggybacks: KalSpin = mode % 4,
        // KalPulseTarget = mode % 3, KalProtect = motion % 4, KalAnchor and
        // KalFreeze ride the breathe axis -- together they flip every
        // kaleido Spin / Protect / Anchor / PulseTarget / Freeze clause.
        {
            ALSweep s; s.mName = "S4";
            for (U32 k = 0; k < 24; ++k)
                for (U32 b = 0; b <= 1; ++b)
                    for (U32 mo = 0; mo < 12; ++mo)
                    {
                        ALDiopterState st;
                        st.mEnabled = true;
                        st.mToolMode = 1;
                        st.mKalMode = k;
                        st.mCellBreathe = b ? 0.4f : 0.f;
                        st.mKalMotionMode = mo;
                        st.mKalSpinMode = k % 4;
                        st.mKalPulseTarget = k % 3;
                        st.mKalProtectMode = mo % 4;
                        st.mKalProtectAnchor = b ? 1 : 0;
                        st.mKalFreeze = (b != 0);
                        s.mStates.push_back(st);
                    }
            sweeps.push_back(s);
        }

        // S5 -- aperture-shape x pattern-mode (5*4 = 20): Rotation
        // membership {1,2,3}, and WARP_ARMED via the pattern arm.
        {
            ALSweep s; s.mName = "S5";
            for (U32 a = 0; a < 5; ++a)
                for (U32 p = 0; p < 4; ++p)
                {
                    ALDiopterState st;
                    st.mEnabled = true;
                    st.mApertureShape = a;
                    st.mPatternMode = p;
                    s.mStates.push_back(st);
                }
            sweeps.push_back(s);
        }

        // S6 -- focus-mode x lens-mode x provenance (2*2*3 = 12): the
        // three-way Base Distance ambiguity.  Manual focus mode coerces
        // provenance to MANUAL (the resolver never overrides the slider
        // there, pipeline:14204/14213 both require focus_mode == 1).
        // Piggyback: Freeze rides the lens-mode axis for row 13.
        {
            ALSweep s; s.mName = "S6";
            for (U32 fm = 0; fm <= 1; ++fm)
                for (U32 lm = 0; lm <= 1; ++lm)
                    for (U32 pv = 0; pv < 3; ++pv)
                    {
                        ALDiopterState st;
                        st.mEnabled = true;
                        st.mFocusMode = fm;
                        st.mLensFocusMode = lm;
                        st.mBaseFocusProvenance =
                            (fm == 0) ? AL_DIOPTER_FOCUS_MANUAL
                                      : (ALDiopterFocusProvenance)pv;
                        st.mResolvedBaseFocusM =
                            (st.mBaseFocusProvenance ==
                             AL_DIOPTER_FOCUS_MANUAL) ? 8.f : 12.4f;
                        st.mFreeze = (lm == 1);
                        s.mStates.push_back(st);
                    }
            sweeps.push_back(s);
        }

        // S7 -- ghosts-armed x seam-armed x content x profile
        // (2*2*2*5 = 40): the 7 ghost dependents, Seam Double Amount, and
        // Magnify's profile-OR-content rule.
        {
            ALSweep s; s.mName = "S7";
            for (U32 g = 0; g <= 1; ++g)
                for (U32 sm = 0; sm <= 1; ++sm)
                    for (U32 c = 0; c <= 1; ++c)
                        for (U32 pr = 0; pr < 5; ++pr)
                        {
                            ALDiopterState st;
                            st.mEnabled = true;
                            st.mGhostCount = g ? 3.f : 0.f;
                            st.mSeamPx = sm ? 6.f : 0.f;
                            st.mContent = c;
                            st.mGlassProfile = pr;
                            s.mStates.push_back(st);
                        }
            sweeps.push_back(s);
        }

        // S8 -- character x plane-separation x field-scale x content
        // (2*2*2*2 = 16): the four aberration controls, Surround Max Blur's
        // OR rule, and Magnify Scale's multiplicative gate.  Plane
        // separation is driven by the UNDERLYING distance settings (manual
        // lens mode, Lens Distance equal to / different from Base Distance),
        // never by writing the derived strength_d.
        {
            ALSweep s; s.mName = "S8";
            for (U32 ch = 0; ch <= 1; ++ch)
                for (U32 sep = 0; sep <= 1; ++sep)
                    for (U32 fs = 0; fs <= 1; ++fs)
                        for (U32 c = 0; c <= 1; ++c)
                        {
                            ALDiopterState st;
                            st.mEnabled = true;
                            st.mCharacter = ch ? 1.f : 0.f;
                            st.mLensFocusMode = 1;      // manual lens plane
                            st.mFocusMode = 0;          // manual base plane
                            st.mBaseFocusProvenance = AL_DIOPTER_FOCUS_MANUAL;
                            st.mBaseFocusM = 8.f;
                            st.mResolvedBaseFocusM = 8.f;
                            st.mLensFocusM = sep ? 4.f : 8.f;
                            st.mFieldScale = fs ? 1.f : 0.f;
                            st.mContent = c;
                            s.mStates.push_back(st);
                        }
            sweeps.push_back(s);
        }

        return sweeps;
    }

    const std::vector<ALSweep>& sSweepsRef()
    {
        static const std::vector<ALSweep> sweeps = buildSweeps();
        return sweeps;
    }

    // ---------------------------------------------------------------------
    // Coverage bitmaps and assertions -- verbatim from design doc 2.3.
    // ---------------------------------------------------------------------

    struct ALCoverage
    {
        // [pred][state] -- state 0 = observed false, 1 = observed true.
        // PRED_NONE occupies slot 0 and is never written or checked.
        bool mPred[AL_PRED_COUNT][2] = {};
        // [row][clause][state]; AL_MAX_CLAUSES == 3 per the schema.
        bool mClause[AL_RELEVANCE_COUNT][AL_MAX_CLAUSES][2] = {};
        // [row][state] -- the row's overall relevance verdict.
        bool mRow[AL_RELEVANCE_COUNT][2] = {};
    };

    // Called once per sweep case, after evaluating the table against `st`.
    void alAccumulateCoverage(const ALDiopterState& st, ALCoverage& cov)
    {
        for (S32 p = PRED_NONE + 1; p < AL_PRED_COUNT; ++p)
        {
            cov.mPred[p][alDiopterEvalPred((ALDiopterPred)p, st) ? 1 : 0] = true;
        }

        for (S32 r = 0; r < AL_RELEVANCE_COUNT; ++r)
        {
            const ALDiopterRelevance& row = sRelevance[r];
            // mClauseCount, not a sentinel scan: ALWAYS clauses (mTermCount
            // == 0) are real clauses and are accumulated here like any other.
            for (S32 c = 0; c < row.mClauseCount; ++c)
            {
                const bool pass = alDiopterEvalClause(row, c, st);
                cov.mClause[r][c][pass ? 1 : 0] = true;
            }
            cov.mRow[r][alDiopterEvaluate(row, st) ? 1 : 0] = true;
        }
    }

    void alAssertCoverage(const ALCoverage& cov)
    {
        for (S32 p = PRED_NONE + 1; p < AL_PRED_COUNT; ++p)
        {
            for (S32 s = 0; s < 2; ++s)
            {
                tut::ensure(llformat(
                    "predicate %s never observed %s across the sweep corpus -- "
                    "add a sweep axis that varies it (design doc SS2.3)",
                    alDiopterPredName((ALDiopterPred)p), s ? "true" : "false"),
                    cov.mPred[p][s]);
            }
        }

        for (S32 r = 0; r < AL_RELEVANCE_COUNT; ++r)
        {
            const ALDiopterRelevance& row = sRelevance[r];
            if (row.mUnconditional)
            {
                // diopter_enabled: never irrelevant by design. Assert that
                // the exemption is not being used to hide an untested row.
                tut::ensure("only diopter_enabled may be UNCONDITIONAL",
                            std::string(row.mCtrlName) == "diopter_enabled");
                continue;
            }

            for (S32 s = 0; s < 2; ++s)
            {
                tut::ensure(llformat("row %s never observed %s -- unreachable "
                                     "or always-on rule", row.mCtrlName,
                                     s ? "relevant" : "irrelevant"),
                            cov.mRow[r][s]);
            }

            for (S32 c = 0; c < row.mClauseCount; ++c)
            {
                tut::ensure(llformat("row %s clause %d never PASSES -- "
                                     "unreachable clause", row.mCtrlName, c),
                            cov.mClause[r][c][1]);
                tut::ensure(llformat("row %s clause %d never FAILS -- dead "
                                     "clause, the terms are implied by "
                                     "something else", row.mCtrlName, c),
                            cov.mClause[r][c][0]);
            }
        }
    }

    // The per-case correctness assertion, with set-difference diagnostics
    // (a raw ensure_equals on two std::sets cannot name the offenders).
    void alEnsureSameSet(const std::string& label,
                         const std::set<std::string>& table_set,
                         const std::set<std::string>& oracle_set)
    {
        if (table_set == oracle_set)
        {
            return;
        }
        std::string msg = label + " relevant-set != oracle consumed-set;";
        for (const std::string& name : table_set)
        {
            if (oracle_set.count(name) == 0)
            {
                msg += " table-only:" + name;
            }
        }
        for (const std::string& name : oracle_set)
        {
            if (table_set.count(name) == 0)
            {
                msg += " oracle-only:" + name;
            }
        }
        tut::ensure(msg, false);
    }

    void alRunSweeps(ALCoverage& cov)
    {
        S32 cases = 0;
        for (const ALSweep& sweep : sSweepsRef())          // S0..S8
        {
            for (const ALDiopterState& st : sweep)  // iterates the cross product
            {
                // 1. the correctness assertion: table vs oracle
                alEnsureSameSet(llformat("%s case %d", sweep.mName, cases),
                                alDiopterRelevantSet(st),
                                alOracleConsumedSet(st));
                // 2. the adequacy accumulation
                alAccumulateCoverage(st, cov);
                ++cases;
            }
        }
        tut::ensure_equals("sweep corpus size changed unexpectedly",
                           cases, 1580);
    }
