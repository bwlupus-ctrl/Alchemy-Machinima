    typedef std::set<std::string> StrSet;

    StrSet setOf(const LLSD& array)
    {
        StrSet out;
        for (LLSD::array_const_iterator it = array.beginArray();
             it != array.endArray(); ++it)
        {
            out.insert(it->asString());
        }
        return out;
    }

    std::vector<StrSet> vecOf(const LLSD& array, size_t expected)
    {
        std::vector<StrSet> out;
        for (LLSD::array_const_iterator it = array.beginArray();
             it != array.endArray(); ++it)
        {
            out.push_back(setOf(*it));
        }
        tut::ensure_equals("oracle branch-array size", out.size(), expected);
        return out;
    }

    std::set<S32> intsOf(const LLSD& array)
    {
        std::set<S32> out;
        for (LLSD::array_const_iterator it = array.beginArray();
             it != array.endArray(); ++it)
        {
            out.insert((S32)it->asInteger());
        }
        return out;
    }

