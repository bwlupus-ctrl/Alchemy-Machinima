#!/usr/bin/env python3
"""Lint the Director Kit v2 XUI tree (DIRECTOR_KIT_P0_SPEC.md section 6.1).

Usage::

    python scripts/code_tools/kit_lint.py --all [--json]
    python scripts/code_tools/kit_lint.py --changed <git-rev> [--json]
    python scripts/code_tools/kit_lint.py panel_dpage_x.xml ... [--json]
    python scripts/code_tools/kit_lint.py --selftest [--json]

The tree is floater_director_v2.xml plus every panel_dpage_*.xml in
skins/default/xui/en.  Cross-file rules (widget names, settings homes) always
read the whole tree; positional file arguments only choose which findings are
printed.  An empty tree lints clean.

Error rules (exit 1): kit-geometry, bottom-attr, kit-row-control, kit-kind-tag,
setting-graph, widget-name, section-cards, setting-home, selector-value,
generated-header.  Warning rules (exit stays 0): help-audit-term, help-empty,
pending-wp (only from an explicit, cited, expiring gate_policy.json entry).
Exit 2 is for command-line, XML or input errors.  Standard library only.

Choices where the spec leaves room:
- Homes come from doc/director_kit/page_sources.json (setting_conflicts[].writable_home,
  bare page keys).  Page keys compare by their last path segment.
- A writer is any kit_row carrying setting plus authored binding attributes;
  lazy-page/rail master indicators are observers. A shortcut is a kit_row with
  shortcut_of="<page>/<row>".
- "Easy card or selector mode-specific block" = the card is listed by the
  page's mode_on mode, or the row sits inside a kit_option.
- Help text is checked when the help attribute is present; "empty" means present and blank.
- --changed REV lints the whole tree when a kit input changed since REV, else reports nothing.
- The measured label-width rule (spec 6.1 "Additional errors") is not implemented here: it needs
  the viewer font and two-line label syntax, which the spec does not pin down.  The runtime audit
  (6.4, measured label errors) covers it.  The label/value round trip is director_page_sources.py --check.
"""

