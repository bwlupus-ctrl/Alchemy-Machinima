@dataclass
class Node:
    tag: str
    attrs: dict[str, str]
    line: int
    parent: Node | None
    children: list[Node] = field(default_factory=list)

    def walk(self) -> Iterator[Node]:
        yield self
        for child in self.children:
            yield from child.walk()

    def ancestor(self, tag: str) -> Node | None:
        node = self.parent
        while node is not None and node.tag != tag:
            node = node.parent
        return node


@dataclass
class Tree:
    name: str
    root: Node
    page: str
    header: tuple[str, str, str | None, str | None] | None


@dataclass(frozen=True)
class Finding:
    file: str
    line: int
    severity: str
    rule: str
    message: str

    def render(self) -> str:
        return f"{self.file}:{self.line}: {self.severity}: {self.rule}: {self.message}"


