def bare(page_key: str) -> str:
    return page_key.rsplit("/", 1)[-1]


def split_list(value: str | None) -> list[str]:
    return [item.strip() for item in (value or "").split(",") if item.strip()]


def err(tree: Tree, node: Node, rule: str, message: str) -> Finding:
    return Finding(tree.name, node.line, "error", rule, message)


def warn(tree: Tree, node: Node, rule: str, message: str) -> Finding:
    return Finding(tree.name, node.line, "warn", rule, message)


def parse_bytes(data: bytes, name: str) -> Node:
    parser = expat.ParserCreate()
    stack: list[Node] = []
    roots: list[Node] = []

    def start(tag: str, attrs: dict[str, str]) -> None:
        parent = stack[-1] if stack else None
        node = Node(tag, dict(attrs), parser.CurrentLineNumber, parent)
        if parent is None:
            roots.append(node)
        else:
            parent.children.append(node)
        stack.append(node)

    def end(_tag: str) -> None:
        stack.pop()

    parser.StartElementHandler = start
    parser.EndElementHandler = end
    try:
        parser.Parse(data, True)
    except expat.ExpatError as exc:
        raise ValueError(f"{name}: XML error: {exc}") from exc
    return roots[0]


def discover(xui_dir: Path) -> list[Path]:
    if not xui_dir.is_dir():
        return []
    paths = list(xui_dir.glob(PAGE_GLOB))
    floater = xui_dir / FLOATER_FILE
    if floater.is_file():
        paths.append(floater)
    return sorted(paths, key=lambda path: path.name)


def load_tree(path: Path) -> Tree:
    data = path.read_bytes()
    root = parse_bytes(data, path.name)
    match = HEADER_RE.search(data.decode("utf-8", errors="replace"))
    kit_page = next((node for node in root.walk() if node.tag == "kit_page" and node.attrs.get("page")), None)
    page = bare(kit_page.attrs["page"]) if kit_page is not None else ""
    header = (match.group(1), match.group(2), match.group(3), match.group(4)) if match else None
    return Tree(path.name, root, page, header)


def llsd_pairs(node: ElementTree.Element) -> Iterator[tuple[str, ElementTree.Element]]:
    key: str | None = None
    for child in node:
        if child.tag == "key":
            key = child.text or ""
        elif key is not None:
            yield key, child
            key = None


def load_settings_graph(settings_dir: Path) -> tuple[dict[str, str], list[str]]:
    """Return setting name -> LLSD Type, following Global/PerAccount bases and their Include arrays."""
    index_path = settings_dir / "settings_files.xml"
    if not index_path.is_file():
        raise ValueError(f"{index_path}: settings index not found")
    index = ElementTree.parse(index_path).getroot()
    bases: list[tuple[str, bool]] = []
    for node in index.iter("file"):
        # persistent="false" files (session.xml) are runtime-only and are not declared bases.
        if node.get("persistent") == "false":
            continue
        if node.get("name") in ("Global", "PerAccount") and node.get("file_name"):
            bases.append((node.get("file_name", ""), node.get("required", "true") != "false"))
    types: dict[str, str] = {}
    problems: list[str] = []
    seen: set[str] = set()

    def visit(file_name: str, required: bool) -> None:
        if file_name in seen:
            return
        seen.add(file_name)
        path = settings_dir / file_name
        if not path.is_file():
            if required:
                problems.append(file_name)
            return
        top = ElementTree.parse(path).getroot().find("map")
        if top is None:
            return
        for key, value in llsd_pairs(top):
            if key == "Include":
                for item in value.iter("string"):
                    visit((item.text or "").strip(), True)
            elif value.tag == "map":
                for sub_key, sub_value in llsd_pairs(value):
                    if sub_key == "Type":
                        types.setdefault(key, (sub_value.text or "").strip())
                        break

    for file_name, required in bases:
        visit(file_name, required)
    return types, problems


def load_homes(path: Path) -> dict[str, str]:
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    homes: dict[str, str] = {}
    for entry in data.get("setting_conflicts", []):
        home = entry.get("writable_home")
        if home:
            homes[entry["setting"]] = bare(home)
    return homes


def load_allow(kit_dir: Path) -> set[str]:
    path = kit_dir / "kit_lint_allow.json"
    if not path.is_file():
        return set()
    return set(json.loads(path.read_text(encoding="utf-8")).get("names", []))


def load_policy(kit_dir: Path) -> dict:
    path = kit_dir / "gate_policy.json"
    defaults = {"pending_settings": {}, "pending_homes": {}, "shared_writers": {},
                "same_page_mode_writers": {}, "help_audit_allow": {},
                "code_kind_exceptions": {}}
    if not path.is_file():
        return defaults
    data = json.loads(path.read_text(encoding="utf-8"))
    return defaults | {
        "pending_settings": data.get("pending_settings", {}),
        "pending_homes": data.get("pending_homes", {}),
        "shared_writers": data.get("shared_writers", {}),
        "same_page_mode_writers": data.get("same_page_mode_writers", {}),
        "help_audit_allow": data.get("help_audit_allow", {}),
        "code_kind_exceptions": data.get("code_kind_exceptions", {}),
    }


def sha16(path: Path) -> str | None:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16] if path.is_file() else None


def source_bundle_sha(kit_dir: Path) -> str | None:
    config_path = kit_dir / "kit_pages.json"
    generator = kit_dir.parent / "director_kit_gen.py"
    v1 = XUI_DIR / "floater_director.xml"
    if not all(path.is_file() for path in (config_path, generator, v1)):
        return None
    config = json.loads(config_path.read_text(encoding="utf-8"))
    paths = [generator, v1]
    paths += [XUI_DIR / name for page in config.get("p0_pages", {}).values()
              for name in page.get("v1_sources", [])]
    if not all(path.is_file() for path in paths):
        return None
    digest = hashlib.sha256()
    for path in sorted(set(paths), key=lambda item: item.as_posix()):
        digest.update(path.resolve().as_posix().encode("utf-8")); digest.update(b"\0")
        digest.update(path.read_bytes()); digest.update(b"\0")
    return digest.hexdigest()[:16]


def check_header(tree: Tree, inputs_sha: tuple[str | None, str | None, str | None, str | None]) -> list[Finding]:
    if tree.header is None:
        return [Finding(tree.name, 1, "error", "generated-header",
                        "missing GENERATED header with the mockup and kit_pages.json sha256 values")]
    mock, kit, vcam, bundle = inputs_sha
    if mock is None or kit is None:
        return [Finding(tree.name, 1, "error", "generated-header",
                        "generation input missing: director_mockup_data.json or kit_pages.json")]
    expected = (mock, kit, vcam, bundle)
    # The compact unit fixtures predate source-bundle hashing and deliberately
    # have no generator/v1 inputs. Real trees must carry the third digest.
    if tree.header != expected:
        return [Finding(tree.name, 1, "error", "generated-header",
                        f"stale generation: header has {tree.header}, inputs are {expected}")]
    return []


def check_geometry(tree: Tree) -> list[Finding]:
    out: list[Finding] = []
    for node in tree.root.walk():
        if not (node.tag.startswith("kit_") or node.tag == "light_rig_map"):
            continue
        if node.tag == "kit_shell":
            continue
        if node.parent is not None and node.parent.tag == "kit_row":
            continue  # control children are checked by kit-row-control
        if node.tag == "kit_page" and node.attrs.get("legacy") in ("true", "1"):
            allowed: tuple[str, ...] = ("width", "height")
        elif node.parent is not None and node.parent.tag == "kit_bar":
            allowed = ("width", "height")
        else:
            allowed = ()
        for attr in GEOMETRY_ATTRS:
            if attr in node.attrs and attr not in allowed:
                out.append(err(tree, node, "kit-geometry",
                               f"kit tag <{node.tag}> has geometry attribute '{attr}'"))
    return out


def check_bottom(tree: Tree) -> list[Finding]:
    return [err(tree, node, "bottom-attr", "bottom= is not allowed; use top and height")
            for node in tree.root.walk() if "bottom" in node.attrs]


def check_rows(tree: Tree) -> list[Finding]:
    out: list[Finding] = []
    for node in tree.root.walk():
        if node.tag != "kit_row":
            continue
        kind = node.attrs.get("kind", "")
        if kind not in KIND_TAGS:
            out.append(err(tree, node, "kit-kind-tag", f"unknown kit_row kind '{kind}'"))
            continue
        expected = 0 if kind in NO_CONTROL_KINDS else 1
        if len(node.children) != expected:
            out.append(err(tree, node, "kit-row-control",
                           f"kind '{kind}' needs {expected} control child(ren), found {len(node.children)}"))
        allowed = KIND_TAGS[kind]
        for child in node.children:
            if expected and allowed is not None and child.tag not in allowed:
                out.append(err(tree, child, "kit-kind-tag",
                               f"kind '{kind}' expects control <{'/'.join(sorted(allowed))}>, found <{child.tag}>"))
            stripped = [attr for attr in ROW_STRIPPED_ATTRS if attr in child.attrs]
            if child.tag in LABEL_STRIPPED_TAGS and "label" in child.attrs:
                stripped.append("label")
            for attr in stripped:
                out.append(err(tree, child, "kit-row-control",
                               f"control child <{child.tag}> has stripped attribute '{attr}'"))
            text_width = child.attrs.get("text_width")
            if child.tag == "slider":
                if text_width != "52":
                    out.append(err(tree, child, "kit-row-control",
                                   "slider control child needs text_width='52' (P0 spec 3.3)"))
            elif text_width is not None:
                out.append(err(tree, child, "kit-row-control",
                               f"control child <{child.tag}> has stripped attribute 'text_width'"))
            if child.tag == "compass_dial":
                if child.attrs.get("kit_geometry") != "true" or child.attrs.get("show_readout") != "false":
                    out.append(err(tree, child, "kit-row-control",
                                   "compass_dial needs kit_geometry='true' and show_readout='false'"))
                for attr in ("can_edit_text", "show_text"):
                    if attr in child.attrs:
                        out.append(err(tree, child, "kit-row-control",
                                       f"compass_dial has slider-only attribute '{attr}'"))
    return out


def check_setting_ref(tree: Tree, node: Node, name: str, label: str,
                      allowed: tuple[str, ...] | None, types: dict[str, str],
                      pending: dict[str, str], release_wp: int | None = None) -> list[Finding]:
    if name not in types:
        if name in pending:
            policy = pending[name]
            reason = policy if isinstance(policy, str) else (
                f"pending {policy.get('expires', 'WP?')}: {policy.get('reason', '')} ({policy.get('citation', '')})")
            if isinstance(policy, dict) and release_wp is not None and int(str(policy.get("expires", "WP0")).removeprefix("WP")) <= release_wp:
                return [err(tree, node, "pending-wp", f"expired {reason}")]
            return [warn(tree, node, "pending-wp", f"{label} '{name}': {reason}")]
        return [err(tree, node, "setting-graph", f"{label} '{name}' is not in the viewer settings graph")]
    if allowed and types[name] not in allowed:
        return [err(tree, node, "setting-graph",
                    f"{label} '{name}' is {types[name]}; <{node.tag}> needs {'/'.join(allowed)}")]
    return []


def check_settings(tree: Tree, types: dict[str, str], pending: dict[str, object],
                   code_exceptions: dict[str, object], release_wp: int | None = None) -> list[Finding]:
    out: list[Finding] = []
    for node in tree.root.walk():
        for attr, value in node.attrs.items():
            if attr == "control_name":
                out += check_setting_ref(tree, node, value, attr, TAG_TYPES.get(node.tag), types, pending, release_wp)
            elif attr == "setting":
                # A code-bound row uses setting only as watch/reset/amber metadata;
                # its presentation widget is not a control-variable binding.
                exempt = node.attrs.get("widget", "") in code_exceptions
                allowed = (KIND_TYPES.get(node.attrs.get("kind", ""))
                           if node.tag == "kit_row" and not exempt else None)
                out += check_setting_ref(tree, node, value, attr, allowed, types, pending, release_wp)
            elif attr in ATTR_TYPES:
                out += check_setting_ref(tree, node, value, attr, ATTR_TYPES[attr], types, pending, release_wp)
            elif attr in LIST_SETTING_ATTRS:
                for name in split_list(value):
                    out += check_setting_ref(tree, node, name, attr, None, types, pending, release_wp)
        if node.tag == "kit_row" and node.attrs.get("bind") == "setting":
            controls = [child.attrs.get("control_name") for child in node.children if "control_name" in child.attrs]
            if controls != [node.attrs.get("setting")]:
                out.append(err(tree, node, "setting-graph",
                               f"bind=\"setting\" row needs its control child's control_name to equal "
                               f"setting '{node.attrs.get('setting', '')}'"))
    return out


def check_stale_pending_settings(types: dict[str, str], pending: dict[str, object]) -> list[Finding]:
    """Pending is only for unresolved dependencies; resolved entries are policy rot."""
    return [
        Finding("gate_policy.json", 1, "error", "stale-policy",
                f"pending_settings '{name}' is stale: the setting now exists as {types[name]}")
        for name in sorted(set(types) & set(pending))
    ]


def check_cards(tree: Tree) -> list[Finding]:
    out: list[Finding] = []
    for page in tree.root.walk():
        if page.tag != "kit_page":
            continue
        cards = {node.attrs.get("id", ""): node for node in page.walk() if node.tag == "kit_card"}
        listed: set[str] = set()
        for section in (node for node in page.walk() if node.tag == "kit_page.section"):
            for card_id in split_list(section.attrs.get("cards")):
                if card_id not in cards:
                    out.append(err(tree, section, "section-cards",
                                   f"section '{section.attrs.get('id', '')}' names unknown card '{card_id}'"))
                listed.add(card_id)
        for mode in (node for node in page.walk() if node.tag == "kit_page.mode"):
            for card_id in split_list(mode.attrs.get("cards")):
                if card_id not in cards:
                    out.append(err(tree, mode, "section-cards",
                                   f"mode '{mode.attrs.get('name', '')}' names unknown card '{card_id}'"))
        for card_id in sorted(cards):
            if card_id not in listed:
                out.append(err(tree, cards[card_id], "section-cards", f"card '{card_id}' is in no section"))
    return out


def check_options(tree: Tree) -> list[Finding]:
    return [err(tree, node, "selector-value", f"kit_option '{node.attrs.get('label', '')}' has no value")
            for node in tree.root.walk() if node.tag == "kit_option" and "value" not in node.attrs]


def check_help(tree: Tree, allow: dict[str, object], release_wp: int | None = None) -> list[Finding]:
    out: list[Finding] = []
    for node in tree.root.walk():
        if "help" not in node.attrs:
            continue
        text = node.attrs["help"]
        if not text.strip():
            out.append(warn(tree, node, "help-empty", "empty help text"))
            continue
        match = AUDIT_TERM_RE.search(text)
        if match:
            subject = node.attrs.get("widget") or node.attrs.get("name") or ""
            policy = allow.get(subject)
            if policy is not None:
                if isinstance(policy, str):
                    if policy.lower().startswith("pending wp"):
                        out.append(warn(tree, node, "pending-wp", policy))
                    continue
                if policy.get("text") == text:
                    expiry = int(str(policy.get("expires", "WP0")).removeprefix("WP"))
                    if release_wp is not None and expiry <= release_wp:
                        out.append(err(tree, node, "pending-wp",
                                       f"expired {policy.get('expires')}: {policy.get('reason')} ({policy.get('citation')})"))
                        continue
                    if str(policy.get("expires", "")).upper() != "WP12":
                        out.append(warn(tree, node, "pending-wp",
                                        f"pending {policy.get('expires')}: {policy.get('reason')} ({policy.get('citation')})"))
                    continue
            out.append(warn(tree, node, "help-audit-term",
                            f"help text matches audit term '{match.group(0)}'"))
    return out


def check_names(trees: list[Tree], allow: set[str]) -> list[Finding]:
    out: list[Finding] = []
    first: dict[str, tuple[str, int]] = {}
    for tree in trees:
        occurrences: list[tuple[str, Node]] = []
        for node in tree.root.walk():
            name = node.attrs.get("name", "")
            if name:
                occurrences.append((name, node))
            if node.tag == "kit_page":
                for attr in ("master_widget", "mode_widget"):
                    if node.attrs.get(attr): occurrences.append((node.attrs[attr], node))
            if node.tag in {"kit_card", "kit_option"} and node.attrs.get("enable_widget"):
                occurrences.append((node.attrs["enable_widget"], node))
            if node.tag == "kit_row":
                widget = node.attrs.get("widget", "")
                if widget:
                    occurrences.append((node.attrs.get("label_name") or widget + "_label", node))
                    if node.attrs.get("reset_settings"): occurrences.append((widget + "_reset", node))
                    if node.attrs.get("kind") in {"slider", "number", "dial", "arc"}:
                        occurrences.append((widget + "_value", node))
                        if node.attrs.get("unit"): occurrences.append((widget + "_unit", node))
                    if node.attrs.get("kind") == "toggle": occurrences.append((widget + "_state", node))
        for name, node in occurrences:
            if name not in first:
                first[name] = (tree.name, node.line)
            elif name not in allow:
                where = first[name]
                out.append(err(tree, node, "widget-name",
                               f"widget name '{name}' is already used at {where[0]}:{where[1]}"))
    return out


def collect_writers(trees: list[Tree]) -> dict[str, list[Writer]]:
    writers: dict[str, list[Writer]] = defaultdict(list)
    for tree in trees:
        easy_modes = {node.attrs.get("mode_on", "") for node in tree.root.walk() if node.tag == "kit_page"}
        listed = {card_id for node in tree.root.walk() if node.tag == "kit_page.mode"
                  if node.attrs.get("name", "") in easy_modes
                  for card_id in split_list(node.attrs.get("cards"))}
        for node in tree.root.walk():
            # The lazy shell reads page masters only to draw tab/rail on-pips.
            # It cannot mutate the setting and is not a second writable home.
            if node.tag == "kit_lazy_page":
                continue
            row_node = node.parent if node.parent is not None and node.parent.tag == "kit_row" else None
            card = node if node.tag == "kit_card" else node.ancestor("kit_card")
            easy = node.ancestor("kit_option") is not None or (
                card is not None and card.attrs.get("id", "") in listed)
            shortcut = row_node.attrs.get("shortcut_of", "") if row_node is not None else ""
            if node.tag == "kit_row" and node.attrs.get("setting"):
                control_node = node.children[0] if node.children else node
                writers[node.attrs["setting"]].append(Writer(
                    tree, control_node, node.attrs["setting"], tree.page, node.attrs.get("widget", ""),
                    node, node.attrs.get("shortcut_of", ""), easy, "setting"))
            for attr in WRITER_ATTRS:
                if attr == "control_name" and row_node is not None:
                    continue
                setting = node.attrs.get(attr, "")
                if not setting:
                    continue
                if row_node is not None:
                    row = row_node.attrs.get("widget", "")
                else:
                    row = node.attrs.get("name") or node.attrs.get("id") or node.tag
                writers[setting].append(Writer(tree, node, setting, tree.page, row, row_node, shortcut, easy, attr))
    return writers


def check_shortcut(w: Writer, home: Writer, home_page: str) -> list[Finding]:
    tree, setting = w.tree, w.setting
    target_page, sep, target_row = w.shortcut.rpartition("/")
    if not sep:
        return [err(tree, w.node, "setting-home", f"shortcut_of '{w.shortcut}' must be '<home page>/<home row>'")]
    if bare(target_page) != home_page or target_row != home.row:
        return [err(tree, w.node, "setting-home",
                    f"shortcut_of '{w.shortcut}' is not the home of '{setting}' ('{home_page}/{home.row}')")]
    out: list[Finding] = []
    if w.row_node is None:
        return [err(tree, w.node, "setting-home", "shortcut_of is only valid on a kit_row")]
    if not w.easy:
        out.append(err(tree, w.node, "setting-home",
                       f"shortcut '{w.row}' is outside an Easy card or selector mode-specific block"))
    mine = {k: w.row_node.attrs.get(k) for k in ROW_META_ATTRS}
    mine.update({k: w.node.attrs.get(k) for k in CONTROL_META_ATTRS})
    theirs = {k: home.row_node.attrs.get(k) if home.row_node is not None else None for k in ROW_META_ATTRS}
    theirs.update({k: home.node.attrs.get(k) for k in CONTROL_META_ATTRS})
    for key in ROW_META_ATTRS + CONTROL_META_ATTRS:
        if mine[key] != theirs[key]:
            out.append(err(tree, w.node, "setting-home",
                           f"shortcut '{w.row}' drifts from its home: {key}={mine[key]!r}, home has {theirs[key]!r}"))
    return out


def load_source_row_meta(kit_dir: Path) -> dict[tuple[str, str], dict[str, str | None]]:
    path = kit_dir / "director_mockup_data.json"
    if not path.is_file():
        return {}
    data = json.loads(path.read_text(encoding="utf-8"))
    result: dict[tuple[str, str], dict[str, str | None]] = {}
    mapping = {"kind": "k", "min_val": "mn", "max_val": "mx", "decimals": "dc",
               "unit": "unit", "increment": "st", "decimal_digits": "dc"}
    for group in data.get("groups", []):
        for page in group.get("pages", []):
            for card in page.get("cards", []):
                rows = list(card.get("rows", []))
                rows.extend(row for option in card.get("opts", []) for row in option.get("rows", []))
                for row in rows:
                    widget = row.get("w")
                    if widget:
                        result[(str(page.get("name", "")), str(widget))] = {
                            attr: None if row.get(source) is None else str(row.get(source)).lower()
                            if isinstance(row.get(source), bool) else str(row.get(source))
                            for attr, source in mapping.items()
                        }
    return result


def check_homes(trees: list[Tree], homes: dict[str, str], pending: dict[str, str],
                shared: dict[str, object], release_wp: int | None = None,
                mode_writers: dict[str, object] | None = None,
                source_rows: dict[tuple[str, str], dict[str, str | None]] | None = None) -> list[Finding]:
    out: list[Finding] = []
    mode_writers = mode_writers or {}
    source_rows = source_rows or {}
    writers = collect_writers(trees)
    for setting in sorted(writers):
        occurrences = sorted(writers[setting], key=lambda w: (w.tree.name, w.node.line))
        pages = {w.page for w in occurrences}
        home_page = homes.get(setting)
        if home_page is None:
            # One-home is a cross-page authorship rule. Easy/Advanced, master,
            # card-enable and selector occurrences on one page are one home.
            shared_policy = shared.get(setting)
            shared_attrs = set(shared_policy.get("attrs", [])) if isinstance(shared_policy, dict) else set()
            shared_expired = (isinstance(shared_policy, dict) and release_wp is not None
                              and int(str(shared_policy.get("expires", "WP0")).removeprefix("WP")) <= release_wp)
            if shared_policy and not shared_expired and {w.attr for w in occurrences} <= shared_attrs:
                continue
            mode_policy = mode_writers.get(setting)
            mode_attrs = set(mode_policy.get("attrs", [])) if isinstance(mode_policy, dict) else set()
            mode_expired = (isinstance(mode_policy, dict) and release_wp is not None
                            and int(str(mode_policy.get("expires", "WP0")).removeprefix("WP")) <= release_wp)
            explicit_local_shortcut = False
            if len(occurrences) == 2 and len(pages) == 1:
                canonical = [w for w in occurrences if not w.shortcut]
                aliases = [w for w in occurrences if w.shortcut]
                if len(canonical) == 1 and len(aliases) == 1:
                    target_page, sep, target_row = aliases[0].shortcut.rpartition("/")
                    explicit_local_shortcut = (bool(sep)
                                               and bare(target_page) == canonical[0].page
                                               and target_row == canonical[0].row
                                               and aliases[0].easy)
            if (mode_policy and not mode_expired and len(occurrences) == 2 and len(pages) == 1
                    and ({w.easy for w in occurrences} == {True, False} or explicit_local_shortcut)
                    and {w.attr for w in occurrences} <= mode_attrs):
                continue
            legitimate_pair = (len(occurrences) == 2 and len(pages) == 1
                               and {w.easy for w in occurrences} == {True, False}
                               and all(w.row_node is not None for w in occurrences)
                               and all(
                                   ({key: occurrences[0].row_node.attrs.get(key) for key in ROW_META_ATTRS}
                                    | {key: occurrences[0].node.attrs.get(key) for key in CONTROL_META_ATTRS})
                                   == ({key: other.row_node.attrs.get(key) for key in ROW_META_ATTRS}
                                       | {key: other.node.attrs.get(key) for key in CONTROL_META_ATTRS})
                                   for other in occurrences[1:]))
            if len(occurrences) > 1 and not legitimate_pair:
                for w in occurrences[1:]:
                    out.append(err(w.tree, w.node, "setting-home",
                                   f"setting '{setting}' has {len(occurrences)} writers and no home "
                                   f"in page_sources.json"))
            continue
        home: Writer | None = None
        for w in occurrences:
            if w.page == home_page and not w.shortcut:
                if home is None:
                    home = w
                else:
                    out.append(err(w.tree, w.node, "setting-home",
                                   f"second writer of '{setting}' on its home page '{home_page}' (row '{w.row}')"))
        if home is None:
            first = occurrences[0]
            if setting in pending:
                policy = pending[setting]
                message = policy if isinstance(policy, str) else (
                    f"pending {policy.get('expires')}: {policy.get('reason')} ({policy.get('citation')})")
                expired = (isinstance(policy, dict) and release_wp is not None
                           and int(str(policy.get("expires", "WP0")).removeprefix("WP")) <= release_wp)
                out.append((err if expired else warn)(first.tree, first.node, "pending-wp",
                                                       ("expired " if expired else "") + message))
                for w in occurrences:
                    if not w.shortcut or w.row_node is None:
                        continue
                    target_page, sep, target_row = w.shortcut.rpartition("/")
                    expected = source_rows.get((bare(target_page), target_row)) if sep else None
                    if expected is None:
                        out.append(err(w.tree, w.node, "setting-home",
                                       f"shortcut_of '{w.shortcut}' has no source-data home row"))
                        continue
                    actual = {key: w.row_node.attrs.get(key) for key in ROW_META_ATTRS}
                    actual.update({key: w.node.attrs.get(key) for key in CONTROL_META_ATTRS})
                    for key in ROW_META_ATTRS + CONTROL_META_ATTRS:
                        if actual[key] != expected[key]:
                            out.append(err(w.tree, w.node, "setting-home",
                                           f"shortcut '{w.row}' drifts from pending home: "
                                           f"{key}={actual[key]!r}, home has {expected[key]!r}"))
            else:
                out.append(err(first.tree, first.node, "setting-home",
                               f"home page '{home_page}' has no writer of '{setting}'"))
        for w in occurrences:
            if w is home or (home is not None and w.page == home_page and not w.shortcut):
                continue
            if not w.shortcut:
                out.append(err(w.tree, w.node, "setting-home",
                               f"unlisted second writer of '{setting}' on '{w.page or w.tree.name}' "
                               f"(home is '{home_page}', not a declared shortcut)"))
            elif home is None:
                if setting not in pending:
                    out.append(err(w.tree, w.node, "setting-home",
                                   f"shortcut of '{setting}' has no home writer on '{home_page}'"))
            else:
                out += check_shortcut(w, home, home_page)
    return out


def check_tree(tree: Tree, types: dict[str, str], inputs_sha: tuple[str | None, str | None, str | None, str | None],
               policy: dict, release_wp: int | None = None) -> list[Finding]:
    return (check_header(tree, inputs_sha) + check_geometry(tree) + check_bottom(tree)
            + check_rows(tree) + check_settings(tree, types, policy["pending_settings"], policy["code_kind_exceptions"], release_wp) + check_cards(tree)
            + check_options(tree) + check_help(tree, policy["help_audit_allow"], release_wp))


def lint(inputs: Inputs) -> Report:
    paths = discover(inputs.xui_dir)
    if not paths:
        return Report([], [])
    trees = [load_tree(path) for path in paths]
    types, problems = load_settings_graph(inputs.settings_dir)
    homes = load_homes(inputs.page_sources)
    allow = load_allow(inputs.kit_dir)
    policy = load_policy(inputs.kit_dir)
    inputs_sha = (sha16(inputs.kit_dir / "director_mockup_data.json"), sha16(inputs.kit_dir / "kit_pages.json"),
                  sha16(inputs.kit_dir / "vcam_page.json"), source_bundle_sha(inputs.kit_dir))
    findings: list[Finding] = [
        Finding("settings_files.xml", 1, "error", "setting-graph", f"settings include '{name}' is missing")
        for name in problems
    ]
    findings += check_stale_pending_settings(types, policy["pending_settings"])
    for tree in trees:
        findings += check_tree(tree, types, inputs_sha, policy, inputs.release_wp)
    findings += check_names(trees, allow)
    findings += check_homes(trees, homes, policy["pending_homes"], policy["shared_writers"],
                            inputs.release_wp, policy.get("same_page_mode_writers", {}),
                            load_source_row_meta(inputs.kit_dir))
    findings.sort(key=lambda f: (f.file, f.line, f.rule, f.message))
    return Report([tree.name for tree in trees], findings)


def changed_kit_inputs(rev: str) -> list[str]:
    proc = subprocess.run(["git", "-C", str(ROOT), "diff", "--name-only", rev, "--"],
                          capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise ValueError(proc.stderr.strip() or f"git diff {rev} failed")
    prefixes = ("indra/newview/skins/default/xui/en/floater_director_v2.xml",
                "indra/newview/skins/default/xui/en/panel_dpage_",
                "scripts/code_tools/director_kit/", "scripts/code_tools/kit_lint.py",
                "doc/director_kit/page_sources.json", "indra/newview/app_settings/")
    return [line for line in proc.stdout.splitlines() if line.startswith(prefixes)]


def emit(report: Report, as_json: bool) -> int:
    errors = [f for f in report.findings if f.severity == "error"]
    warnings = [f for f in report.findings if f.severity == "warn"]
    if as_json:
        print(json.dumps({"files": report.files, "errors": len(errors), "warnings": len(warnings),
                          "findings": [asdict(f) for f in report.findings]}, indent=2))
    else:
        for finding in report.findings:
            print(finding.render())
        print(f"kit_lint: {len(errors)} error(s), {len(warnings)} warning(s) in {len(report.files)} kit file(s)")
    return 1 if errors else 0


SELFTEST_CASES: tuple[tuple[str, str | None, str, str], ...] = (
    ("clean", None, "", "every rule passes on the clean tree"),
    ("fail/geometry", "kit-geometry", "error", "kit_row with left="),
    ("fail/row_control", "kit-row-control", "error", "control child with width="),
    ("fail/kind_tag", "kit-kind-tag", "error", "toggle row with a combo_box child"),
    ("fail/widget_name", "widget-name", "error", "duplicate name without allow entry"),
    ("fail/setting_graph", "setting-graph", "error", "missing setting and type mismatch"),
    ("fail/section_cards", "section-cards", "error", "unknown card and card in no section"),
    ("fail/generated_header", "generated-header", "error", "stale sha256 in header"),
    ("fail/bottom", "bottom-attr", "error", "bottom= on a plain element"),
    ("fail/setting_home", "setting-home", "error", "unlisted second writer, no shortcut"),
    ("fail/shortcut_home", "setting-home", "error", "shortcut outside Easy block with drifted max"),
    ("fail/selector_value", "selector-value", "error", "kit_option without value"),
    ("fail/help_term", "help-audit-term", "warn", "help text with audit term"),
    ("fail/help_empty", "help-empty", "warn", "blank help attribute"),
)


def run_selftest(as_json: bool) -> int:
    kit = FIXTURES / "kit"
    settings = FIXTURES / "settings"
    homes = FIXTURES / "page_sources.json"
    passed = True
    reports: list[dict[str, object]] = []

    def record(name: str, ok: bool, detail: str) -> None:
        nonlocal passed
        passed = passed and ok
        reports.append({"fixture": name, "passed": ok, "detail": detail})
        if not as_json:
            print(f"{'PASS' if ok else 'FAIL'} {name}: {detail}")

    for name, rule, severity, _description in SELFTEST_CASES:
        try:
            report = lint(Inputs(FIXTURES / name, kit, settings, homes))
        except ValueError as exc:
            record(name, False, f"error: {exc}")
            continue
        if rule is None:
            ok = not report.findings
            detail = f"{len(report.findings)} finding(s)"
        else:
            ok = any(f.rule == rule and f.severity == severity for f in report.findings)
            detail = f"{len(report.findings)} finding(s), expects {severity} {rule}"
        record(name, ok, detail)

    probe_node = Node("kit_card", {}, 7, None)
    probe_tree = Tree("policy_fixture.xml", probe_node, "fixture_tab", None)
    pending = check_setting_ref(probe_tree, probe_node, "FixtureDeferred", "sel_setting",
                                COMBO, {}, {"FixtureDeferred": "pending WP2: fixture citation"})
    record("pending_setting_policy",
           len(pending) == 1 and pending[0].rule == "pending-wp" and pending[0].severity == "warn",
           "explicit missing setting is reported as pending-wp")
    stale_pending = check_stale_pending_settings(
        {"FixtureLanded": "S32"},
        {"FixtureLanded": {"expires": "WP2", "reason": "fixture", "citation": "fixture"}},
    )
    record("R1V_N2_stale_pending_setting",
           len(stale_pending) == 1 and stale_pending[0].severity == "error"
           and stale_pending[0].rule == "stale-policy",
           "a pending dependency that now resolves is an error")

    help_node = Node("kit_row", {"widget": "fixture_launcher", "help": "Open Lightbox."}, 8, None)
    help_tree = Tree("help_policy_fixture.xml", help_node, "fixture_tab", None)
    pending_help = check_help(help_tree, {"fixture_launcher": "pending WP10: fixture citation"})
    allowed_help = check_help(help_tree, {"fixture_launcher": "intentional external editor"})
    record("help_policy",
           len(pending_help) == 1 and pending_help[0].rule == "pending-wp" and not allowed_help,
           "pending help is reported; intentional external-editor help is explicitly allowed")

    lazy_node = Node("kit_lazy_page", {"master_setting": "FixtureEnabled"}, 9, None)
    lazy_tree = Tree("lazy_policy_fixture.xml", lazy_node, "", None)
    record("lazy_master_observer",
           "FixtureEnabled" not in collect_writers([lazy_tree]),
           "lazy-page master metadata is not a writable home")

    # WP3 adversarial review R1 (K1-K8).  Keep these named after the review
    # fixtures so a future relaxation cannot silently reopen the same holes.
    page = Node("kit_page", {"master_widget": "dup_switch"}, 1, None)
    card = Node("kit_card", {"name": "kc_a", "id": "a", "enable_widget": "dup_switch"}, 2, page)
    page.children = [card]
    k1 = check_names([Tree("k1.xml", page, "fixture", None)], set())
    record("R1_K1_kit_created_names", any(f.rule == "widget-name" for f in k1),
           "master/card-enable runtime names collide")

    def writer_tree(name: str, page_name: str, widget: str, setting: str,
                    easy: bool = False, shortcut: str = "", maximum: str = "1") -> Tree:
        root = Node("kit_page", ({"mode_on": "Easy"} if easy else {}), 1, None)
        if easy:
            mode = Node("kit_page.mode", {"name": "Easy", "cards": "easy"}, 2, root)
            root.children.append(mode)
        card_id = "easy" if easy else "advanced"
        card_node = Node("kit_card", {"name": "kc_" + card_id, "id": card_id}, 3, root)
        row = Node("kit_row", {"kind": "slider", "widget": widget, "setting": setting,
                               "bind": "code", "max_val": maximum, **({"shortcut_of": shortcut} if shortcut else {})}, 4, card_node)
        control = Node("slider", {"name": widget, "increment": "1"}, 5, row)
        row.children = [control]; card_node.children = [row]; root.children.append(card_node)
        return Tree(name, root, page_name, None)

    k2_trees = [writer_tree("k2a.xml", "same", "one", "K2"),
                writer_tree("k2b.xml", "same", "two", "K2")]
    record("R1_K2_same_page_writer", bool(check_homes(k2_trees, {}, {}, {})),
           "unrelated same-page writers are rejected")
    mode_pair = [writer_tree("mode_easy.xml", "same", "easy", "ModePair", easy=True),
                 writer_tree("mode_advanced.xml", "same", "advanced", "ModePair", maximum="2")]
    mode_policy = {"ModePair": {"attrs": ["setting"], "expires": "WP12"}}
    record("R2_exact_mode_writer_policy",
           not check_homes(mode_pair, {}, {}, {}, None, mode_policy),
           "one exact Easy/Advanced policy permits presentation differences")
    k3_trees = [writer_tree("k3home.xml", "home", "home_row", "K3"),
                writer_tree("k3other.xml", "other", "other_row", "K3")]
    record("R1_K3_code_writer", bool(check_homes(k3_trees, {"K3": "home"}, {}, {})),
           "code-bound row setting participates in one-home")
    home_writer = collect_writers([writer_tree("home.xml", "home", "home_row", "K4")])["K4"][0]
    bad_location = collect_writers([writer_tree("other.xml", "other", "shortcut", "K4",
                                                shortcut="home/home_row")])["K4"][0]
    record("R1_K4_easy_location", any("outside an Easy card" in f.message
                                        for f in check_shortcut(bad_location, home_writer, "home")),
           "Advanced-only shortcut is rejected")
    drift = collect_writers([writer_tree("other.xml", "other", "shortcut", "K4", easy=True,
                                         shortcut="home/home_row", maximum="99")])["K4"][0]
    record("R1_K5_pending_home_drift", bool(check_shortcut(drift, home_writer, "home")),
           "shortcut metadata is compared even while rollout home is pending")
    k6row = Node("kit_row", {"kind": "toggle", "widget": "bad_type", "setting": "FloatSetting", "bind": "code"}, 1, None)
    k6tree = Tree("k6.xml", k6row, "fixture", None)
    record("R1_K6_code_kind_type", bool(check_settings(k6tree, {"FloatSetting": "F32"}, {}, {})),
           "code-bound toggle over F32 is rejected")
    k7map = Node("light_rig_map", {"view_setting": "NoSuchSettingXYZ"}, 1, None)
    k7tree = Tree("k7.xml", k7map, "fixture", None)
    record("R1_K7_map_settings", bool(check_settings(k7tree, {}, {}, {})),
           "light-map state attributes resolve through settings graph")
    k8row = Node("kit_row", {"kind": "dial", "widget": "dial"}, 1, None)
    k8dial = Node("compass_dial", {"name": "dial"}, 2, k8row); k8row.children = [k8dial]
    record("R1_K8_dial_contract", bool(check_rows(Tree("k8.xml", k8row, "fixture", None))),
           "dial requires kit geometry and suppresses its internal readout")

    with tempfile.TemporaryDirectory() as empty:
        report = lint(Inputs(Path(empty), kit, settings, homes))
        record("empty_tree", not report.findings and not report.files, "0 kit files, 0 findings")

    if as_json:
        print(json.dumps({"passed": passed, "fixtures": reports}, indent=2))
    elif passed:
        print("Self-test passed: geometry, bottom, row/control, kind/tag, setting graph, names, "
              "sections/cards, generated header, homes/shortcuts, selector values, help warnings")
    return 0 if passed else 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--all", action="store_true", help="lint every Director kit XUI file")
    mode.add_argument("--changed", metavar="GIT_REV", help="lint when a kit input changed since GIT_REV")
    mode.add_argument("--selftest", action="store_true", help="run bundled fixtures")
    parser.add_argument("--json", action="store_true", help="emit machine-readable JSON")
    parser.add_argument("--release-wp", type=int, choices=range(1, 13), metavar="N",
                        help="treat policy entries expiring at or before WPN as errors")
    parser.add_argument("files", nargs="*", help="kit XUI files to report on")
    args = parser.parse_args()

    if args.selftest:
        return run_selftest(args.json)
    if not (args.all or args.changed or args.files):
        parser.error("choose --all, --changed GIT_REV, --selftest, or files")

    inputs = Inputs(XUI_DIR, KIT_DIR, SETTINGS_DIR, PAGE_SOURCES, args.release_wp)
    try:
        if args.changed and not changed_kit_inputs(args.changed):
            if args.json:
                print(json.dumps({"files": [], "errors": 0, "warnings": 0, "findings": []}, indent=2))
            else:
                print(f"kit_lint: no kit input changed since {args.changed}")
            return 0
        report = lint(inputs)
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 2

    if args.files:
        known = set(report.files)
        wanted = {Path(item).name for item in args.files}
        unknown = sorted(wanted - known)
        if unknown:
            print(f"not a Director kit file in {XUI_DIR}: {', '.join(unknown)}", file=sys.stderr)
            return 2
        report = Report(sorted(wanted), [f for f in report.findings if f.file in wanted])
    return emit(report, args.json)


