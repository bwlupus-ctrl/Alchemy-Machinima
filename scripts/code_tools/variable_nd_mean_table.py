"""Offline VND normalization table generator and scalar host-lookup reference.

Only regeneration integrates; viewer recomputes use eight table reads. The tan
coordinate t/(1+t) includes both limiting frusta, log2(aspect) covers 1:16..16:1,
and symmetry reduces the ring to 0..pi/2. No dial/grade enters this integral.
"""
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / 'indra/newview/allenslooks_vnd_mean.h'
NT, NA, NR = 17, 65, 65


def generate():
    import numpy as np
    coord = (np.arange(128) + .5) / 64 - 1
    values = np.empty((NT, NA, NR))
    angles = np.arange(NR) * (math.pi / 2 / (NR - 1))
    for a in range(NA):
        aspect = 2 ** (-4 + a / 8)
        x, y = np.meshgrid(coord * aspect, coord)
        radius = np.hypot(x, y).ravel()
        phi = np.arctan2(y, x).ravel()[:, None] - angles
        axis = math.atan(1 / aspect)
        folded = np.arctan2(abs(np.sin(phi)), abs(np.cos(phi)))
        sector = np.where(folded < axis, axis, math.pi/2 - axis)
        leak = abs(np.sin((folded - axis) * math.pi/2 / sector)) ** .85
        for t in range(NT):
            if t == 0:
                radial = radius ** .25
            elif t == NT - 1:
                radial = np.ones_like(radius)
            else:
                tangent = t / (NT - 1 - t)
                # Corner normalization cancels in the weighted ratio.
                radial = np.arctan(radius * tangent) ** .25
            values[t, a] = radial @ leak / radial.sum()
    lines = ['// Generated by scripts/code_tools/variable_nd_mean_table.py; do not hand edit.',
             '// 17 tan/(1+tan) x 65 log2(aspect) x 65 abs(ring) nodes; F32, 280.6 KiB.',
             '#pragma once', 'static constexpr F32 VND_MEAN[17][65][65] = {']
    for slab in values:
        lines.append('    {')
        for row in slab:
            lines.append('        {' + ','.join(f'{v:.8f}f' for v in row) + '},')
        lines.append('    },')
    lines.append('};')
    HEADER.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def read_table():
    return [float(v) for v in re.findall(r'(\d+\.\d+)f', HEADER.read_text())]


def lookup(table, tangent, aspect, angle):
    """Same scalar math, bounds and trilinear interpolation as the C++ host."""
    if not all(map(math.isfinite, (tangent, aspect, angle))) or tangent <= 0 or aspect <= 0:
        return 0.
    t = min(tangent / (1 + tangent) * 16, 16.)
    a = max(0., min(64., (math.log2(aspect) + 4) * 8))
    r = abs(math.remainder(angle, math.pi)) * (128 / math.pi)
    ti, ai, ri = min(int(t), 15), min(int(a), 63), min(int(r), 63)
    tf, af, rf = t-ti, a-ai, r-ri
    def along_ring(dt, da):
        i = ((ti+dt)*65 + ai+da)*65 + ri
        return table[i] + rf*(table[i+1]-table[i])
    low = along_ring(0, 0)*(1-af) + along_ring(0, 1)*af
    high = along_ring(1, 0)*(1-af) + along_ring(1, 1)*af
    return low + tf*(high-low)


if __name__ == '__main__':
    generate()
