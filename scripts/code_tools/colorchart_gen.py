"""Generate the client colour chart table. No network or third-party packages."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / 'indra/newview/alcolorchartdata.h'
# Lead-verified X-Rite Classic published sRGB set (pre-November 2014).
PATCHES = [
    ('Dark skin', (115,82,68)), ('Light skin', (194,150,130)),
    ('Blue sky', (98,122,157)), ('Foliage', (87,108,67)),
    ('Blue flower', (133,128,177)), ('Bluish green', (103,189,170)),
    ('Orange', (214,126,44)), ('Purplish blue', (80,91,166)),
    ('Moderate red', (193,90,99)), ('Purple', (94,60,108)),
    ('Yellow green', (157,188,64)), ('Orange yellow', (224,163,46)),
    ('Blue', (56,61,150)), ('Green', (70,148,73)),
    ('Red', (175,54,60)), ('Yellow', (231,199,31)),
    ('Magenta', (187,86,149)), ('Cyan', (8,133,161)),
    ('White 9.5', (243,243,242)), ('Neutral 8', (200,200,200)),
    ('Neutral 6.5', (160,160,160)), ('Neutral 5', (122,122,121)),
    ('Neutral 3.5', (85,85,85)), ('Black 2', (52,52,52)),
    ('Linear white', (255,255,255)), ('18% grey', (118,118,118)),
    ('Black', (0,0,0)),
]


def linear(code):
    c = code / 255.
    return c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4


def values():
    return [(.18,)*3 if i == 25 else tuple(map(linear, rgb))
            for i, (_, rgb) in enumerate(PATCHES)]


def rectangles():
    # Integer pixels also define the float quad layout; y grows from the bottom.
    return [(16+(i%6)*144, 736-16-(i//6+1)*144+16, 128, 128)
            if i < 24 else (16+(i-24)*288, 16, 272, 128) for i in range(27)]


def generate():
    rows = []
    for (name, rgb), value, rect in zip(PATCHES, values(), rectangles()):
        rows.append('    {"%s", {%s}, {%s}, {%s}},' %
                    (name, ', '.join(map(str, rgb)),
                     ', '.join(f'{v:.10f}f' for v in value), ', '.join(map(str, rect))))
    return ('// Generated by scripts/code_tools/colorchart_gen.py; do not edit.\n'
            '#ifndef AL_COLOR_CHART_DATA_H\n#define AL_COLOR_CHART_DATA_H\n'
            'namespace ALColorChartData\n{\n'
            'constexpr int WIDTH = 880, HEIGHT = 736, COUNT = 27;\n'
            'constexpr float ASPECT = float(WIDTH) / float(HEIGHT);\n'
            'struct Patch { const char* name; unsigned char srgb[3]; float linear[3]; int rect[4]; };\n'
            'constexpr Patch PATCHES[COUNT] = {\n' + '\n'.join(rows) + '\n};\n}\n#endif\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate().encode('utf-8')
    if args.check:
        assert HEADER.read_bytes() == expected, 'generated chart header differs'
        print('PASS: generated header byte-identical; 27 patches')
    else:
        HEADER.write_bytes(expected)
