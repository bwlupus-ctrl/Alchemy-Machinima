"""Generate the Log calibration chart table and its reference sheet.

Writes indra/newview/alcolorchartlogdata.h (patch table) and
doc/colour_chart_log_reference.md (expected S-Log3 codes per patch).
No network or third-party packages. --check verifies both are current.
"""
from pathlib import Path
import argparse
import math

ROOT = Path(__file__).resolve().parents[2]
HEADER = ROOT / 'indra/newview/alcolorchartlogdata.h'
SHEET = ROOT / 'doc/colour_chart_log_reference.md'
WIDTH, HEIGHT = 1920, 1080
GREY = .18

# Sony S-Gamut3 from linear Rec.709 (same matrix as the viewer's encoder and
# ALColorChart::debugReadback).
SG3 = ((.5660490800, .3427630874, .0911878326),
       (.0769613789, .7990545001, .1239841211),
       (.0223509133, .1086120512, .8690370356))


def srgb_linear(code):
    c = code / 255.
    return c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4


def patches():
    """(name, group, linear rgb, rect x y w h). y grows from the bottom."""
    out = []
    # Row 1: grey wedge, one patch per stop around 18% grey.
    for i, stop in enumerate(range(-8, 7)):
        value = GREY * 2. ** stop
        name = '18% grey' if stop == 0 else f'Grey {stop:+d} stops'
        out.append((name, 'wedge', (value,) * 3, (32 + i * 124, 832, 120, 216)))
    # Row 2: anchors, skin and memory colours.
    anchors = [
        ('Black 0%', (0.,) * 3),
        ('Black 2%', (.02,) * 3),
        ('18% grey ref', (GREY,) * 3),
        ('White 90%', (.9,) * 3),
        ('White 100%', (1.,) * 3),
        ('Dark skin', tuple(map(srgb_linear, (115, 82, 68)))),
        ('Light skin', tuple(map(srgb_linear, (194, 150, 130)))),
        ('Blue sky', tuple(map(srgb_linear, (98, 122, 157)))),
        ('Foliage', tuple(map(srgb_linear, (87, 108, 67)))),
    ]
    for i, (name, value) in enumerate(anchors):
        out.append((name, 'anchor', value, (32 + i * 207, 592, 200, 216)))
    # Row 3: gamut, full saturation then 50% (mixed with equal grey), at 0.5.
    hues = [('Red', (1, 0, 0)), ('Green', (0, 1, 0)), ('Blue', (0, 0, 1)),
            ('Cyan', (0, 1, 1)), ('Magenta', (1, 0, 1)), ('Yellow', (1, 1, 0))]
    gamut = [(f'{n} 100%', tuple(.5 * c for c in rgb)) for n, rgb in hues]
    gamut += [(f'{n} 50%', tuple(.25 + .25 * c for c in rgb)) for n, rgb in hues]
    for i, (name, value) in enumerate(gamut):
        out.append((name, 'gamut', value, (34 + i * 155, 352, 147, 216)))
    # Row 4: log ramp, -8 to +6 stops in 1/8-stop slices. On a waveform this
    # is a straight diagonal when the curve is S-Log3.
    for i in range(112):
        stop = -8. + (i + .5) / 8.
        value = GREY * 2. ** stop
        out.append((f'Ramp {stop:+.4f} stops', 'ramp', (value,) * 3, (64 + i * 16, 32, 16, 296)))
    return out


def slog3(x):
    if x >= .01125:
        code = (420. + 261.5 * math.log10((x + .01) / .19)) / 1023.
    else:
        code = (95. + x * (171.2102946929 - 95.) / .01125) / 1023.
    return min(max(code, 0.), 1.)


def encode(rgb, purity=1., gamut=1):
    """Viewer type-8 encode at exposure 1, EV 0, toe 0, full range."""
    rgb = list(rgb)
    if not (rgb[0] == rgb[1] == rgb[2]):
        y = .2126 * rgb[0] + .7152 * rgb[1] + .0722 * rgb[2]
        rgb = [y + purity * (c - y) for c in rgb]
    if gamut == 1:
        rgb = [sum(SG3[r][c] * rgb[c] for c in range(3)) for r in range(3)]
    return [slog3(max(c, 0.)) for c in rgb]


def header():
    rows = []
    for name, _, value, rect in patches():
        rows.append('    {"%s", {0, 0, 0}, {%s}, {%s}},' %
                    (name, ', '.join(f'{v:.10f}f' for v in value), ', '.join(map(str, rect))))
    return ('// Generated by scripts/code_tools/colorchart_log_gen.py; do not edit.\n'
            '#ifndef AL_COLOR_CHART_LOG_DATA_H\n#define AL_COLOR_CHART_LOG_DATA_H\n'
            '#include "alcolorchartdata.h"\n'
            'namespace ALColorChartLogData\n{\n'
            f'constexpr int WIDTH = {WIDTH}, HEIGHT = {HEIGHT}, COUNT = {len(patches())};\n'
            'constexpr float ASPECT = float(WIDTH) / float(HEIGHT);\n'
            'constexpr ALColorChartData::Patch PATCHES[COUNT] = {\n' + '\n'.join(rows) + '\n};\n}\n#endif\n')


def fmt(codes):
    tens = ' / '.join(f'{round(c * 1023):d}' for c in codes)
    pct = ' / '.join(f'{c * 100:.1f}' for c in codes)
    return tens, pct


def sheet():
    lines = [
        '# Log calibration chart: reference values',
        '',
        '_Generated by `scripts/code_tools/colorchart_log_gen.py`; do not edit._',
        '',
        'Director > Look > Image > Colour chart, **Mode: Log calibration**. The pattern is',
        'drawn unlit and fills the frame (Placement: Camera). It goes through the S-Log3',
        'encoder exactly like the scene does, so these are the values your scopes should read.',
        '',
        '**Settings the numbers assume:** tone mapper S-Log3 (type 8), Log curve S-Log3,',
        'Log gamut S-Gamut3, Exposure 1.00, Log EV 0, Log toe 0, Range Full,',
        'sensor noise off. Greys do not depend on gamut or purity. Gamut and colour patches',
        'are listed for Sensor purity 1.00 and 0.90 (the default).',
        '',
        '**Simulate sensor** (Director > Light > Exposure, off by default) clips like a real',
        'sensor when it is on: the top wedge steps flatten at its clip point (about +3.5 stops',
        'at ISO 100; it moves with ISO) instead of reaching the codes below. Footage shot with',
        'it on does the same. Turn it off to read the bare S-Log3 curve.',
        '',
        'Codes are 10-bit full range (0-1023) and percent of full scale, as R / G / B.',
        'In Magic Bullet Looks set the input to **Sony S-Log3 - S-Gamut3** and check the',
        'grey wedge with the Looks scopes **before** adding any Look tool:',
        '',
        '- What Magic Bullet must receive is the code divided by 1023 (the "0-1" column):',
        '  18% grey 0.411, Black 0% 0.093, White 90% 0.584. Read it with the Looks pixel',
        '  readout or the parade with the Input tool switched off, or on the Vegas scopes',
        '  with no FX on the clip.',
        '- **Levels check (use the Black 0% patch; 18% grey barely moves):**',
        '  - black 0.093 = levels correct;',
        '  - black about 0.035 (white 0.610) = the video was expanded (full range read as legal);',
        '  - black about 0.144 (white 0.563) = the video was squeezed (legal range read as full).',
        '  Fix it in the clip or project levels in Vegas, not with the S-Curve.',
        '- Sony\'s "41% / 3.5% / 61% IRE" figures are the same codes measured on a legal-range',
        '  video scale; they are not what the 0-1 pixel values should read.',
        '- Each wedge step should be the same distance apart (about 77 codes per stop above',
        '  about -5 stops), and the bottom ramp should be a straight diagonal on the waveform.',
        '- After the input transform, the wedge should come out neutral (R = G = B).',
        '',
        'Then add your Look and watch where the wedge and the gamut patches start to clip',
        'or bend.',
        '',
        '## Grey wedge (top row, left to right)',
        '',
        '| Patch | Linear | 10-bit code | 0-1 (what MBL reads) | Sony IRE (legal scale) |',
        '|---|---|---|---|---|',
    ]
    for name, group, value, _ in patches():
        if group == 'wedge':
            code = encode(value)[0]
            ire = (code * 1023. - 64.) / 876. * 100.
            lines.append(f'| {name} | {value[0]:.5f} | {round(code * 1023)} | {code:.3f} | {ire:.1f} |')
    for group, title in (('anchor', 'Anchors, skin and memory colours (second row)'),
                         ('gamut', 'Gamut (third row: 100% saturation, then 50%)')):
        lines += ['', f'## {title}', '',
                  '| Patch | Linear R / G / B | Codes, purity 1.00 | %, purity 1.00 | Codes, purity 0.90 | %, purity 0.90 |',
                  '|---|---|---|---|---|---|']
        for name, patch_group, value, _ in patches():
            if patch_group == group:
                a = fmt(encode(value, 1.))
                b = fmt(encode(value, .9))
                lin = ' / '.join(f'{v:.4f}' for v in value)
                lines.append(f'| {name} | {lin} | {a[0]} | {a[1]} | {b[0]} | {b[1]} |')
    lines += ['', '## Bottom ramp', '',
              '112 slices from -8 to +6 stops around 18% grey, 1/8 stop each (left = darkest).',
              f'Left slice code {round(encode(patches()[-112][2])[0] * 1023)}, '
              f'right slice code {round(encode(patches()[-1][2])[0] * 1023)}.',
              '',
              'If **AlchemyColorChartDebugReadback** is on, the viewer also logs PASS/FAIL per',
              'patch (not the ramp) against these values at your current settings.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {HEADER: header().encode('utf-8'), SHEET: sheet().encode('utf-8')}
    if args.check:
        for path, data in outputs.items():
            assert path.read_bytes() == data, f'{path.name} differs from generator'
        grey = encode((GREY,) * 3)[0]
        assert round(grey * 1023) == 420, grey
        print(f'PASS: log chart header + sheet byte-identical; {len(patches())} patches; 18% grey code 420')
    else:
        for path, data in outputs.items():
            path.write_bytes(data)
