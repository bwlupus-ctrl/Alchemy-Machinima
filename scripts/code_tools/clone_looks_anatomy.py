"""Ground-origin SL rest anatomy; shader literals are generated, never fitted.

Run with --write after changing avatar_skeleton.xml. The safety gate compares
the entire generated block before rendering, so stale/fixture literals fail.
"""
from pathlib import Path
import argparse
import xml.etree.ElementTree as ET
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SHADER = ROOT/'indra/newview/app_settings/shaders/class1/interface/actorghostF.glsl'
BEGIN = '// BEGIN SL SKELETON ANATOMY (generated by clone_looks_anatomy.py)'
END = '// END SL SKELETON ANATOMY'


def anatomy():
    joints = {}
    nodes = {}
    def visit(bone, parent=np.eye(4)):
        vec = lambda key, default: np.fromstring(bone.get(key, default), sep=' ')
        x,y,z = np.radians(vec('rot','0 0 0'))
        rx=np.array([[1,0,0],[0,np.cos(x),-np.sin(x)],[0,np.sin(x),np.cos(x)]])
        ry=np.array([[np.cos(y),0,np.sin(y)],[0,1,0],[-np.sin(y),0,np.cos(y)]])
        rz=np.array([[np.cos(z),-np.sin(z),0],[np.sin(z),np.cos(z),0],[0,0,1]])
        local=np.eye(4);local[:3,:3]=rz@ry@rx@np.diag(vec('scale','1 1 1'));local[:3,3]=vec('pos','0 0 0')
        world=parent@local;name=bone.get('name');joints[name]=world[:3,3];nodes[name]=bone
        for child in bone.findall('bone'):visit(child,world)
    for bone in ET.parse(ROOT/'indra/newview/character/avatar_skeleton.xml').getroot().findall('bone'):visit(bone)
    z=lambda name:float(joints[name][2])
    head=nodes['mHead'].find("collision_volume[@name='HEAD']")
    top=z('mHead')+float(head.get('pos').split()[2])+float(head.get('scale').split()[2])
    values=dict(foot=min(z('mFootLeft'),z('mFootRight')),ankle=z('mAnkleLeft'),
                knee=z('mKneeLeft'),pelvis=z('mPelvis'),chest=z('mChest'),
                shoulder=z('mCollarLeft'),neck=z('mNeck'),head=z('mHead'),
                eye=z('mEyeLeft'),top=top,
                half_width=float(abs(joints['mShoulderLeft'][1])),
                eye_half_width=float(abs(joints['mEyeLeft'][1])))
    return values,joints


def shader_block():
    values,_=anatomy()
    return BEGIN+'\n'+''.join(f'const float sl_{k} = {v:.6f};\n' for k,v in values.items())+END


def verify(source):
    assert BEGIN in source and END in source, 'missing skeleton-derived anatomy block'
    actual=source[source.index(BEGIN):source.index(END)+len(END)]
    assert actual==shader_block(), 'stale/fixture-frame anatomy: run clone_looks_anatomy.py --write'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--write',action='store_true');args=parser.parse_args()
    source=SHADER.read_text(encoding='utf-8')
    if args.write:
        if BEGIN in source:source=source[:source.index(BEGIN)]+shader_block()+source[source.index(END)+len(END):]
        else:source=shader_block()+'\n\n'+source
        SHADER.write_text(source,encoding='utf-8',newline='\n')
    else:verify(source)
    print(anatomy()[0])
